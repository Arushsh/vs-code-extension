import { ProjectInfo, FileNode, FileRelationship } from '../types';

interface GenerateInput {
  projectInfo: ProjectInfo;
  fileTree: FileNode[];
  relationships: Record<string, FileRelationship>;
}

export class ReadmeGenerator {
  generate({ projectInfo, fileTree, relationships }: GenerateInput): string {
    const sections: string[] = [];

    // Title & Description
    sections.push(`# ${this.titleCase(projectInfo.name)}`);
    sections.push('');
    if (projectInfo.description) {
      sections.push(`> ${projectInfo.description}`);
      sections.push('');
    }

    // Badges
    sections.push(this.generateBadges(projectInfo));
    sections.push('');

    // Tech Stack
    sections.push('## 🛠 Tech Stack');
    sections.push('');
    sections.push('| Category | Technology |');
    sections.push('|----------|-----------|');
    sections.push(`| Framework | ${projectInfo.framework} |`);
    sections.push(`| Language | ${projectInfo.language} |`);
    sections.push(`| Package Manager | ${projectInfo.packageManager} |`);
    sections.push(`| Build Tool | ${projectInfo.buildTool} |`);
    sections.push('');

    // Installation
    sections.push('## 🚀 Getting Started');
    sections.push('');
    sections.push('### Prerequisites');
    sections.push('');
    sections.push('- Node.js (v18 or higher recommended)');
    sections.push(`- ${projectInfo.packageManager}`);
    sections.push('');
    sections.push('### Installation');
    sections.push('');
    sections.push('```bash');
    sections.push(`git clone <repository-url>`);
    sections.push(`cd ${projectInfo.name}`);
    sections.push(`${projectInfo.packageManager} install`);
    sections.push('```');
    sections.push('');

    // Scripts
    if (Object.keys(projectInfo.scripts).length > 0) {
      sections.push('## 📜 Available Scripts');
      sections.push('');
      sections.push('```bash');
      for (const [script, cmd] of Object.entries(projectInfo.scripts)) {
        sections.push(`${projectInfo.packageManager} run ${script}   # ${cmd}`);
      }
      sections.push('```');
      sections.push('');
    }

    // Folder Structure
    sections.push('## 📁 Project Structure');
    sections.push('');
    sections.push('```');
    sections.push(this.generateFolderStructure(fileTree, 0, 3));
    sections.push('```');
    sections.push('');

    // Key Dependencies
    const deps = Object.keys(projectInfo.dependencies);
    if (deps.length > 0) {
      sections.push('## 📦 Key Dependencies');
      sections.push('');
      const top = deps.slice(0, 15);
      for (const dep of top) {
        const version = projectInfo.dependencies[dep];
        sections.push(`- \`${dep}\` — ${version}`);
      }
      if (deps.length > 15) {
        sections.push(`- _...and ${deps.length - 15} more_`);
      }
      sections.push('');
    }

    // Entry Point
    sections.push('## 🎯 Entry Point');
    sections.push('');
    sections.push(`The application starts from \`${projectInfo.entryPoint}\`.`);
    sections.push('');

    // Most connected files
    const topFiles = this.getTopConnectedFiles(relationships);
    if (topFiles.length > 0) {
      sections.push('## 🔗 Most Connected Files');
      sections.push('');
      sections.push('_Files with the most imports or that are imported by many others:_');
      sections.push('');
      for (const f of topFiles) {
        const rel = relationships[f];
        sections.push(
          `- \`${f}\` — imports ${rel.imports.length} files, used by ${rel.importedBy.length} files`
        );
      }
      sections.push('');
    }

    // License
    sections.push('## 📄 License');
    sections.push('');
    sections.push('This project is licensed under the [MIT License](LICENSE).');
    sections.push('');

    // Footer
    sections.push('---');
    sections.push('');
    sections.push('_Generated by [CodeAtlas](https://marketplace.visualstudio.com/items?itemName=arush-vishwakarma.codeatlas) — Understand any codebase in minutes._');

    return sections.join('\n');
  }

  private generateBadges(info: ProjectInfo): string {
    const badges: string[] = [];
    badges.push(`![Framework](https://img.shields.io/badge/Framework-${encodeURIComponent(info.framework)}-blue?style=flat-square)`);
    badges.push(`![Language](https://img.shields.io/badge/Language-${encodeURIComponent(info.language)}-green?style=flat-square)`);
    badges.push(`![Version](https://img.shields.io/badge/Version-${encodeURIComponent(info.version)}-orange?style=flat-square)`);
    badges.push(`![License](https://img.shields.io/badge/License-MIT-purple?style=flat-square)`);
    return badges.join(' ');
  }

  private generateFolderStructure(
    nodes: FileNode[],
    depth: number,
    maxDepth: number
  ): string {
    if (depth > maxDepth) return '';
    const lines: string[] = [];
    const prefix = '  '.repeat(depth);

    for (const node of nodes) {
      if (node.type === 'directory') {
        lines.push(`${prefix}${node.name}/`);
        if (node.children && depth < maxDepth) {
          const childLines = this.generateFolderStructure(
            node.children,
            depth + 1,
            maxDepth
          );
          if (childLines) lines.push(childLines);
        }
      } else {
        lines.push(`${prefix}${node.name}`);
      }
    }

    return lines.join('\n');
  }

  private getTopConnectedFiles(
    relationships: Record<string, FileRelationship>
  ): string[] {
    return Object.entries(relationships)
      .filter(
        ([, rel]) =>
          rel.imports.filter((i) => i.isLocal).length > 0 ||
          rel.importedBy.length > 0
      )
      .sort(([, a], [, b]) => {
        const scoreA = a.imports.filter((i) => i.isLocal).length + a.importedBy.length;
        const scoreB = b.imports.filter((i) => i.isLocal).length + b.importedBy.length;
        return scoreB - scoreA;
      })
      .slice(0, 8)
      .map(([key]) => key);
  }

  private titleCase(str: string): string {
    return str
      .replace(/[-_]/g, ' ')
      .replace(/\b\w/g, (c) => c.toUpperCase());
  }
}
